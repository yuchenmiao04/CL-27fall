def configuration(method, output, mode="direct"):
    c = smoke_config(method, output)
    c.update(seed=1993, smoke_feature_dim=6, smoke_depth=2, image_size=16,
             synthetic_per_class=6, epochs=2, batch_size=4, replay_batch_size=3,
             feature_batch_size=4, eval_batch_size=5, cpu_threads=1,
             memory_size=8, memory_per_class=0, basis_rank=2,
             basis_epsilon=0.01, basis_noise_variance=0.01, basis_max_iter=3,
             mean_shrinkage=2.0, crossfit_folds=2, transport_mode=mode)
    return c


def same_state(left, right):
    if isinstance(left, torch.Tensor):
        torch.testing.assert_close(left, right, rtol=0, atol=0)
    elif isinstance(left, np.ndarray):
        np.testing.assert_array_equal(left, right)
    elif isinstance(left, dict):
        assert left.keys() == right.keys()
        for key in left:
            same_state(left[key], right[key])
    elif isinstance(left, (tuple, list)):
        assert len(left) == len(right)
        for a, b in zip(left, right):
            same_state(a, b)
    elif hasattr(left, "__dataclass_fields__"):
        same_state(vars(left), vars(right))
    else:
        assert left == right


@pytest.mark.parametrize("mode", ["direct", "chained"])
def test_reused_native_calls_match_every_stage_weights_heads_replay_moments_and_rng(
    tmp_path, monkeypatch, mode
):
    # Capture after the actual eval_task DataLoader consumed its native base_seed.
    # Comparing only incremental_train would miss an extra evaluation RNG draw.
    captured = {}
    original_factory = runner.factory.get_model

    def factory(name, args):
        # The tiny backbone normally isolates its own initialization. Simulate
        # the real timm constructor's CPU RNG consumption as well: each native
        # run, including readers, must start that constructor from the same seed.
        torch.rand(11)
        learner = original_factory(name, args)
        original_after = learner.after_task
        snapshots = captured.setdefault(str(args["output_dir"]), [])

        def after_task():
            original_after()
            snapshots.append({"learner": learner.checkpoint_state(),
                              "rng": copy.deepcopy(runner.rng_state())})

        learner.after_task = after_task
        return learner

    monkeypatch.setattr(runner.factory, "get_model", factory)
    names = ["er", "history_transport", "plastic_shared_basis"]
    native = {}
    for name in names:
        native[name] = runner.run(configuration(name, tmp_path / ("native_" + name), mode))
    cache = tmp_path / "ce_states"
    for name in names:
        path = tmp_path / ("cohort_" + name)
        reused = runner.run(
            configuration(name, path, mode),
            ce_training_executor=CEStageCache(cache, "record" if name == "er" else "replay"),
        )
        same_state(native[name]["metrics"], reused["metrics"])
        same_state(native[name]["task_diagnostics"], reused["task_diagnostics"])
        same_state(captured[str(tmp_path / ("native_" + name))], captured[str(path)])
        # Full result matrices are still generated by each learner's own head.
        assert len(reused["stages"]) == 3
        for first, second in zip(native[name]["stages"], reused["stages"]):
            same_state({k: v for k, v in first.items() if k != "wall_seconds"},
                       {k: v for k, v in second.items() if k != "wall_seconds"})
        proof = reused["execution"]["ce_training_reuse"]
        assert [r["reused"] for r in proof["stages"]] == [name != "er"] * 3
        assert all(r["request_fingerprint"] for r in proof["stages"])
        checkpoint = torch.load(path / "checkpoint.pt", weights_only=False)
        same_state(checkpoint["rng"], captured[str(path)][-1]["rng"])
    assert len(list(cache.glob("stage_*.pt"))) == 3


@pytest.mark.parametrize("changed,value,expected", [
    ("backbone_lr", 0.002, "hyperparameters"),
    ("batch_size", 5, "effective_combined_batch_sizes_per_epoch"),
    ("split_seed", 7, "data_fingerprint"),
])
def test_mismatched_training_data_or_actual_batch_plan_never_reuses(
    tmp_path, changed, value, expected
):
    cache = tmp_path / "ce_states"
    record = configuration("er", tmp_path / "record")
    record["max_tasks"] = 1
    runner.run(record, ce_training_executor=CEStageCache(cache, "record"))
    candidate = configuration("history_transport", tmp_path / "wrong")
    candidate.update(max_tasks=1, **{changed: value})
    with pytest.raises(CEReuseMismatch, match=expected):
        runner.run(candidate, ce_training_executor=CEStageCache(cache, "replay"))
    assert not (tmp_path / "wrong" / "results.json").exists()


def test_corrupt_post_training_state_is_rejected_before_installation(tmp_path):
    cache = tmp_path / "ce_states"
    config = configuration("er", tmp_path / "record")
    config["max_tasks"] = 1
    runner.run(config, ce_training_executor=CEStageCache(cache, "record"))
    filename = cache / "stage_000.pt"
    record = torch.load(filename, weights_only=False)
    key = next(iter(record["body"]))
    record["body"][key].view(-1)[0] += 0.25
    torch.save(record, filename)
    candidate = configuration("history_transport", tmp_path / "wrong")
    candidate["max_tasks"] = 1
    with pytest.raises(CEReuseMismatch, match="tensors do not match"):
        runner.run(candidate, ce_training_executor=CEStageCache(cache, "replay"))


def test_changed_raw_training_bytes_are_not_hidden_by_same_ids_or_manifest(tmp_path, monkeypatch):
    cache = tmp_path / "ce_states"
    config = configuration("er", tmp_path / "record")
    config["max_tasks"] = 1
    runner.run(config, ce_training_executor=CEStageCache(cache, "record"))
    original_get = runner.ProtocolDataManager.get_dataset

    def changed_get(self, indices, source, mode, *args, **kwargs):
        result = original_get(self, indices, source, mode, *args, **kwargs)
        if source == "train" and mode == "train":
            result.images = result.images.copy()
            result.images[0, 0, 0, 0] ^= np.uint8(1)
        return result

    monkeypatch.setattr(runner.ProtocolDataManager, "get_dataset", changed_get)
    candidate = configuration("history_transport", tmp_path / "wrong")
    candidate["max_tasks"] = 1
    with pytest.raises(CEReuseMismatch, match="current"):
        runner.run(candidate, ce_training_executor=CEStageCache(cache, "replay"))


def test_record_refuses_overwrite_and_missing_reader_never_trains(tmp_path):
    cache = tmp_path / "ce_states"
    config = configuration("er", tmp_path / "record")
    config["max_tasks"] = 1
    runner.run(config, ce_training_executor=CEStageCache(cache, "record"))
    again = dict(config, output_dir=str(tmp_path / "again"))
    with pytest.raises(CEReuseMismatch, match="overwrite"):
        runner.run(again, ce_training_executor=CEStageCache(cache, "record"))
    (cache / "stage_000.pt").unlink()
    candidate = configuration("history_transport", tmp_path / "missing")
    candidate["max_tasks"] = 1
    with pytest.raises(CEReuseMismatch, match="Missing complete"):
        runner.run(candidate, ce_training_executor=CEStageCache(cache, "replay"))


def test_original_runner_checkpoint_from_reused_run_resumes_independently(tmp_path):
    cache = tmp_path / "ce_states"
    record = configuration("er", tmp_path / "record")
    runner.run(record, ce_training_executor=CEStageCache(cache, "record"))
    short = configuration("history_transport", tmp_path / "short")
    short["max_tasks"] = 1
    runner.run(short, ce_training_executor=CEStageCache(cache, "replay"))
    resumed = runner.run(dict(short, max_tasks=None, output_dir=str(tmp_path / "resume"),
                              resume=str(tmp_path / "short" / "checkpoint.pt")))
    native = runner.run(configuration("history_transport", tmp_path / "native"))
    same_state(resumed["metrics"], native["metrics"])
    same_state(resumed["task_diagnostics"], native["task_diagnostics"])
    a = torch.load(tmp_path / "resume" / "checkpoint.pt", weights_only=False)
    b = torch.load(tmp_path / "native" / "checkpoint.pt", weights_only=False)
    same_state(a["learner"], b["learner"])
    same_state(a["rng"], b["rng"])


def test_cohort_cli_and_readout_only_hpo_replay(tmp_path):
    configs = []
    for name in ["er", "history_transport", "plastic_shared_basis"]:
        path = tmp_path / (name + ".json")
        c = configuration(name, tmp_path / name)
        c.update(epochs=1, max_tasks=2)
        path.write_text(json.dumps(c))
        configs.append(path)
    root = Path(__file__).resolve().parents[1]
    command = [sys.executable, str(root / "scripts/run_ce_cohort.py"), "--configs"]
    command += [str(p) for p in configs]
    command += ["--trajectory-dir", str(tmp_path / "ce"), "--report", str(tmp_path / "report.json")]
    process = subprocess.run(command, cwd=root, capture_output=True, text=True, timeout=120)
    assert process.returncode == 0, process.stdout + process.stderr
    report = json.loads((tmp_path / "report.json").read_text())
    assert report["status"] == "complete"
    assert [r["ce_mode"] for r in report["runs"]] == ["record", "replay", "replay"]
    assert report["runs"][0]["execution_role"] == "internal_shared_ce_driver"
    saved_driver = json.loads((tmp_path / "er" / "config.json").read_text())
    assert saved_driver["execution_role"] == "internal_shared_ce_driver"
    # Change only analytic-head parameters, while keeping every CE precondition.
    candidate = json.loads(configs[2].read_text())
    candidate.update(output_dir=str(tmp_path / "new_head"), basis_rank=1,
                     basis_noise_variance=0.02, map_ridge=0.2)
    path = tmp_path / "new_head.json"
    path.write_text(json.dumps(candidate))
    process = subprocess.run(
        [sys.executable, str(root / "scripts/run_ce_cohort.py"), "--configs", str(path),
         "--trajectory-dir", str(tmp_path / "ce"), "--report", str(tmp_path / "head_report.json"),
         "--replay-only"], cwd=root, capture_output=True, text=True, timeout=120,
    )
    assert process.returncode == 0, process.stdout + process.stderr
    result = json.loads((tmp_path / "new_head" / "results.json").read_text())
    assert all(r["reused"] for r in result["execution"]["ce_training_reuse"]["stages"])


@pytest.mark.parametrize("mode", ["direct", "chained"])
def test_prefix_cohort_extends_own_checkpoints_without_overwriting_trajectory(
    tmp_path, mode
):
    from cl27.ce_trajectory import file_hash
    from scripts.run_ce_cohort import main as cohort_main

    names = ["er", "history_transport", "plastic_shared_basis"]
    prefixes, extensions = [], []
    for name in names:
        path = tmp_path / (name + "_prefix.json")
        config = configuration(name, tmp_path / (name + "_prefix"), mode)
        config.update(epochs=1, max_tasks=1)
        path.write_text(json.dumps(config))
        prefixes.append(path)
    cohort_main(["--configs", *map(str, prefixes), "--trajectory-dir", str(tmp_path / "ce"),
                 "--report", str(tmp_path / "prefix_report.json")])
    first_stage = tmp_path / "ce" / "stage_000.pt"
    unchanged = file_hash(first_stage)
    for name, prefix in zip(names, prefixes):
        path = tmp_path / (name + "_extend.json")
        config = json.loads(prefix.read_text())
        config.update(max_tasks=3, output_dir=str(tmp_path / (name + "_extend")),
                      resume=str(tmp_path / (name + "_prefix") / "checkpoint.pt"))
        path.write_text(json.dumps(config))
        extensions.append(path)
    cohort_main(["--configs", *map(str, extensions), "--trajectory-dir", str(tmp_path / "ce"),
                 "--report", str(tmp_path / "extension_report.json")])
    assert file_hash(first_stage) == unchanged
    assert sorted(p.name for p in (tmp_path / "ce").glob("stage_*.pt")) == [
        "stage_000.pt", "stage_001.pt", "stage_002.pt"
    ]
    for name in names:
        config = configuration(name, tmp_path / (name + "_native"), mode)
        config.update(epochs=1, max_tasks=3)
        native = runner.run(config)
        extension = json.loads((tmp_path / (name + "_extend") / "results.json").read_text())
        same_state(extension["metrics"], native["metrics"])
        same_state(extension["task_diagnostics"], native["task_diagnostics"])
        resumed = torch.load(tmp_path / (name + "_extend") / "checkpoint.pt", weights_only=False)
        whole = torch.load(tmp_path / (name + "_native") / "checkpoint.pt", weights_only=False)
        same_state(resumed["learner"], whole["learner"])
        same_state(resumed["rng"], whole["rng"])
        proof = extension["execution"]["ce_training_reuse"]
        assert [s["task"] for s in proof["stages"]] == [1, 2]
